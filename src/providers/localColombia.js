/**
 * Proveedor local — devuelve resultado inmediato sin latencia de red.
 * Si el BIN no está en la tabla local, lanza error para que el aggregator
 * use los proveedores externos como fallback.
 */
async function localColombia(bin /*, signal */) {
  // Probar prefijos de 6, 7 y 8 dígitos (de más específico a menos)
  for (let len = Math.min(bin.length, 8); len >= 6; len--) {
    const prefix = bin.slice(0, len);
    const slug = BIN_INDEX[prefix];
    if (slug) {
      return {
        source: 'local-colombia',
        bank: BANK_NAMES[slug] || slug,
        bankSlug: slug,
        scheme: BANK_SCHEME[slug] || 'VISA',
        type: 'debit',
        country: 'CO',
      };
    }
  }
  throw new Error('BIN not in local Colombian table');
}

